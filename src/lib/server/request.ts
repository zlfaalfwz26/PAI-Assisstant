import "server-only";

/** Alamat IP klien (dari header proxy/hosting). */
export function clientIp(request: Request): string {
  const forwarded = request.headers.get("x-forwarded-for");
  if (forwarded) {
    const first = forwarded.split(",")[0]?.trim();
    if (first) return first;
  }
  return request.headers.get("x-real-ip")?.trim() || "local";
}

/**
 * Tolak permintaan lintas situs dari browser (perlindungan CSRF ringan).
 * Permintaan tanpa header Origin/Sec-Fetch-Site (mis. curl) tetap dibatasi
 * oleh rate limit dan, untuk admin, oleh cookie sesi.
 */
export function isSameOrigin(request: Request): boolean {
  const fetchSite = request.headers.get("sec-fetch-site");
  if (fetchSite && fetchSite !== "same-origin" && fetchSite !== "none") return false;
  const origin = request.headers.get("origin");
  if (!origin) return true;
  const host = request.headers.get("x-forwarded-host") ?? request.headers.get("host");
  try {
    return new URL(origin).host === host;
  } catch {
    return false;
  }
}
